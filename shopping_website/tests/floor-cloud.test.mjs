import assert from 'node:assert/strict';
import {machineState,updateMachineCycles,machineMotion,resourceStations} from '../static/js/factory-floor-cloud.mjs';
const now=Date.parse('2026-11-11T00:00:00Z');
const row={ResourceID:7,recorded_at:new Date(now).toISOString(),Busy:true};
assert.equal(machineState(row,now),'busy');
let cycles=updateMachineCycles(new Map(),[row],now);
assert.equal(machineMotion(cycles.get('C'),now+2000).progress,.5);
cycles=updateMachineCycles(cycles,[{...row,recorded_at:new Date(now+3000).toISOString()}],now+3000);
assert.equal(cycles.get('C').start,now,'Repeated Busy records must not restart a stroke');
assert.equal(machineMotion(cycles.get('C'),now+5000).progress,1);
assert.equal(machineMotion(cycles.get('C'),now+400000).active,false,'Old record must stop without waiting for a poll');
cycles=updateMachineCycles(cycles,[{...row,Busy:false}],now+6000);
assert.equal(cycles.get('C').state,'idle');
cycles=updateMachineCycles(cycles,[row],now+7000);
assert.equal(cycles.get('C').start,now+7000,'A new Busy edge starts a new stroke');
for(const key of ['ErrorL0','ErrorL1','ErrorL2'])assert.equal(machineState({...row,[key]:true},now),'error');
assert.equal(machineState({...row,recorded_at:'2020-01-01T00:00:00Z'},now),'stale');
assert.equal(machineState({...row,recorded_at:'2026-11-11T00:00:00'},now),'unknown');
assert.equal(machineState({...row,recorded_at:'2026-11-12T00:00:00Z'},now),'unknown');
assert.equal(machineState({...row,Busy:null},now),'unknown');
assert.equal(machineState(undefined,now),'unknown');
assert.equal(updateMachineCycles(cycles,[],now).size,0);
assert.equal(resourceStations[9],undefined,'Do not invent which mobile robot is R1');
console.log('Passed: MES station mapping, all error levels, single Busy-edge cycle, stale/unknown/future records, missing data.');
